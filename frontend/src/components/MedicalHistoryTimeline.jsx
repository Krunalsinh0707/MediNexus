import { useEffect, useState } from 'react';
import { getMyMedicalHistory, getPatientMedicalHistory } from '../services/medicalHistoryService';
import { historyDateParams, historyError, provenanceLabel } from '../pages/medicalHistoryUi';

export default function MedicalHistoryTimeline({ patientId = null }) {
  const [items, setItems] = useState([]);
  const [cursor, setCursor] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [from, setFrom] = useState('');
  const [through, setThrough] = useState('');
  const [filters, setFilters] = useState({});

  useEffect(() => {
    let active = true;
    const request = patientId ? getPatientMedicalHistory(patientId, { limit: 25, ...filters })
      : getMyMedicalHistory({ limit: 25, ...filters });
    request.then(data => {
      if (active) { setItems(data.items || []); setCursor(data.next_cursor || null); setError(''); }
    }).catch(err => {
      if (active) { setItems([]); setCursor(null); setError(historyError(err)); }
    }).finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [patientId, filters]);

  const loadMore = async () => {
    if (!cursor || loading) return;
    setLoading(true); setError('');
    try {
      const params = { limit: 25, ...filters, cursor };
      const page = patientId ? await getPatientMedicalHistory(patientId, params) : await getMyMedicalHistory(params);
      setItems(current => [...current, ...(page.items || [])]);
      setCursor(page.next_cursor || null);
    } catch (err) { setError(historyError(err)); }
    finally { setLoading(false); }
  };

  const applyFilters = (event) => {
    event.preventDefault();
    if (from && through && from > through) {
      setError('The start date must be on or before the end date.');
      return;
    }
    setLoading(true); setError(''); setItems([]); setCursor(null);
    setFilters(historyDateParams(from, through));
  };

  return <section className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm space-y-4" aria-label="Medical history timeline">
    <div><h2 className="text-lg font-bold text-slate-900">Medical history timeline</h2>
      <p className="text-sm text-slate-500">Events are shown by documented event time; vitals use measurement time. Source labels indicate what was reviewed or generated by AI.</p></div>
    <form onSubmit={applyFilters} className="flex flex-wrap items-end gap-3 text-sm">
      <label className="space-y-1">From <input aria-label="History from date" type="date" value={from} onChange={e => setFrom(e.target.value)} className="block rounded-lg border border-slate-300 p-2" /></label>
      <label className="space-y-1">Through <input aria-label="History through date" type="date" value={through} onChange={e => setThrough(e.target.value)} className="block rounded-lg border border-slate-300 p-2" /></label>
      <button type="submit" className="rounded-lg bg-teal-700 px-4 py-2 text-white font-semibold">Apply dates</button>
      <button type="button" onClick={() => { setFrom(''); setThrough(''); setLoading(true); setFilters({}); }} className="rounded-lg border border-slate-300 px-4 py-2">Clear</button>
    </form>
    {error && <p role="alert" className="rounded-lg bg-rose-50 p-3 text-sm text-rose-800">{error}</p>}
    {loading && items.length === 0 ? <p role="status">Loading medical history…</p> : !error && items.length === 0 ? <p>No medical history events are available for this period.</p> : null}
    <ol className="divide-y divide-slate-100">{items.map(item => <li key={item.id} className="py-4 space-y-1">
      <div className="flex flex-wrap items-center gap-2"><h3 className="font-semibold text-slate-900">{item.title}</h3>
        <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${item.provenance === 'ai_generated_assessment' ? 'bg-amber-100 text-amber-900' : 'bg-teal-50 text-teal-800'}`}>{provenanceLabel(item.provenance)}</span></div>
      <p className="text-xs text-slate-500">{new Date(item.occurred_at).toLocaleString()} · {item.status || 'Status not recorded'}{item.corrected ? ' · Superseded by correction' : ''}</p>
      {item.summary && <p className="whitespace-pre-wrap text-sm text-slate-700">{item.summary}</p>}
      {patientId && item.details && Object.keys(item.details).length > 0 && <details className="text-sm text-slate-600"><summary className="cursor-pointer">Recorded details</summary>
        <dl className="mt-2 space-y-1">{Object.entries(item.details).map(([key, value]) => value == null ? null : <div key={key}><dt className="inline font-semibold">{key.replaceAll('_', ' ')}: </dt><dd className="inline whitespace-pre-wrap">{typeof value === 'object' ? JSON.stringify(value) : String(value)}</dd></div>)}</dl></details>}
    </li>)}</ol>
    {cursor && <button type="button" disabled={loading} onClick={loadMore} className="rounded-lg border border-teal-700 px-4 py-2 text-sm font-semibold text-teal-800 disabled:opacity-50">{loading ? 'Loading…' : 'Load more history'}</button>}
  </section>;
}
